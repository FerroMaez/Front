function normalizar(valor) {
  return String(valor || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ')
}

export function getMedidasProducto(nombre, linea) {
  const producto = normalizar(nombre)
  const claveLinea = normalizar(linea) + '|' + producto
  const claveExcel = ALIAS_PRODUCTO[claveLinea] || producto
  return MEDIDAS_EXCEL[claveExcel] || []
}
